# This prompt is used to classify each generated S2R step as either a correct
# step (CS) or an extra step (ES) relative to the ground-truth S2Rs.
S2R_JUDGE_PROMPT = """# Task Summary

You are an experienced Android application developer. Your task is to **evaluate the quality of automatically generated steps to reproduce (S2Rs) of a bug** in an Android app by **comparing them to human-written (ground truth) S2Rs**. Use the evaluation metrics described below to perform this comparison.

---

# You are provided with:

- **Evaluation metrics** with detailed definitions.  
- A list of **ground truth S2Rs**, each with a unique ID and description.  
- A list of **generated S2Rs**, each with a unique ID and description.

---

# Evaluation Metrics

1. **Correct Step (CS):** A generated step matches a ground truth step if the actions they describe are **semantically equivalent**, even if wording or IDs differ. 
   - If a generated step indicates that an action should be performed **_n_ times** (either by repeating the step or explicitly stating the repetition), and the same step appears **_n_ times** in the ground truth, then the **Correct Step (CS) count should be _n_**.   
2. **Missing Step (MS):** A ground truth step that has **no semantically equivalent step** in the generated list.  
3. **Extra Step (ES):** A generated step that does **not match any** ground truth step.  
   - If a generated step appears more times than it does in the ground truth, count the **additional instances** as extra steps (ES).

---

# Matching Criteria

1. Use the **natural language description** as the primary basis for matching.
  - Focus on the **core action and user intent**, not exact phrasing or additional explanatory text.
  - Consider actions using different but interchangeable terms (e.g., "Tap" vs. "Click", "Press" vs. "Select") as equivalent.
  - Ignore additional context or explanations in a step (e.g., "to apply the changes", "to continue", "to grant permissions") **if the main action remains unchanged**.
  - For example:
    - `"Open the Family Finance application"` matches `"Open App"`.
    - `"Tap the 'OK' button to apply the changes"` matches `"Click OK"`.
    - `"Click the floating button"` matches `"Tap the FAB"`.
2. Steps with matching IDs are **definitely equivalent**.
3. Steps with different IDs can still be equivalent if they represent the **same user interaction**.
4. When in doubt, match based on **semantic similarity** and **user intention**, not on UI labels or verbosity.
5. If a generated step contains additional descriptive context (e.g., "to apply the changes"), ignore it when comparing if it doesn't alter the user action being performed.

---

# Instructions

1. For each step in the **generated S2Rs**, try to find a matching step in the **ground truth S2Rs** following the **Matching Criteria**.
2. Assign either CS or ES labels to each **generated S2Rs** according to their definition.
3. Do not need to assign an MS label to the **generated S2Rs**.
4. Return your response in JSON format (see the **Response Format** below), with a top-level `"steps"` field containing one dictionary per generated step. Each dictionary must include:
  - "generated_step": one generated step in one dictionary
  - "label": the assigned label of that generated step, i.e., either CS or ES
  - "matched_gt_step": if the label is CS, then the matched ground truth step; blank otherwise
5. **Do not include any explanation or notes in the output.**

---

# Ground Truth S2Rs
{ground_truth_s2rs}

---

# Generated S2Rs
{generated_s2rs}

---

# Response Format

Return only the structured output matching the provided schema.

**Do not include anything else in the response.**
"""


