INFO_ELEMENTS_JUDGE_PROMPT = """# Task Summary

You are an experienced Android application developer. Your task is to **evaluate the quality** of the **Information Elements** for **Observed Behavior (OB)** and **Expected Behavior (EB)** in Android app bug reports generated by an automated approach.
You will compare them against **human-created ground truth Information Elements** and assign the appropriate **Quality Labels**.

---

# You are provided with:

- Definitions of the **Information Elements** to evaluate.
- **Quality Labels** with definitions.
- Human-created ground truth **Information Elements** (with OB and EB).
- Approach-generated **Information Elements** (with OB and EB).

---

# Definition of the Information Elements

- **Buggy Behavior** (What buggy behavior is observed by the user?): The specific buggy behavior (i.e., the problem) reported in the bug.
- **Triggering GUI Interactions** (What application interaction(/s) triggers the bug?): The user interaction(/s) on the application that triggers the bug.
- **Triggering Screen References** (Which application screen causes the bug and/or where the bug was observed?): The application screen where performing the interaction causes the bug and/or the screen where the bug was observed.
- **Correct Behavior** (What application behavior is expected by the user?): The specific correct application behavior that should happen instead of the buggy behavior.

---

# Quality Labels

- **Correct**: The **generated Information Element** contains the meaning of the **ground truth Information Element**, even if it uses different wording, synonyms, or includes extra contextual details. As long as the **core meaning of the ground truth is present**, it is Correct.
- **Incomplete**: The **generated Information Element** contains part of the **ground truth Information Element** but leaves out an essential detail, making it only a partial match.
- **Ambiguous**: The **generated Information Element** is vague, unclear, or can be interpreted in multiple ways compared to the **ground truth Information Element**.
- **Missing**: The **generated Information Element** does not contain any information (e.g., “N/A”).
- **Incorrect**: The **generated Information Element** is completely different from the ground truth.

---

# Instructions

1. Analyze each **generated Information Element**, including the OB and EB descriptions, one by one.
2. Compare each **generated Information Element** with the **ground truth Information Element** based on **semantic meaning**, not exact wording.
   - Minor rewordings, expansions, or equivalent variations (e.g., different phrasing, broader/narrower scope, or navigation vs. selection actions) are acceptable as long as the **core meaning** remains the same.
3. Assign each **generated Information Element** a quality label: **Correct, Incomplete, Ambiguous, Missing, or Incorrect**, based on the definitions.
4. **Do not include any explanation or notes in the output.**

---

# Ground Information Elements with OB and EB
{ground_truth_info_elements}

---

# Generated Elements with OB and EB
{generated_info_elements}

---

# Response Format
Return only the structured output matching the provided schema.

**Do not include anything else in the response.**
"""
